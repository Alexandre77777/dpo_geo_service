def load_presets(filepath="tags_presets.json"):
    """
    Загружает пресеты тегов из JSON-файла конфигурации.
    
    Зачем выносить конфигурацию в файл?
    ------------------------------------
    1. Изменение параметров без редактирования кода
    2. Возможность иметь несколько конфигураций для разных задач
    3. Упрощение развёртывания (DevOps может менять настройки)
    4. Версионирование конфигурации отдельно от кода
    
    Параметры:
    ----------
    filepath : str
        Путь к JSON-файлу с конфигурацией
    
    Возвращает:
    -----------
    list[dict]
        Список словарей вида:
        {
            "name": "Школы",           # Отображаемое имя
            "key": "amenity",          # OSM-ключ
            "value": "school",         # OSM-значение
            "buffer": 1600             # Радиус буфера в метрах
        }
    
    Пример:
    -------
    >>> presets = load_presets()
    >>> presets[0]["name"]
    'Школы'
    """
    # Явно указываем UTF-8 для поддержки кириллицы в названиях
    with open(filepath, "r", encoding="utf-8") as f:
        # Парсим JSON и возвращаем только список пресетов
        return json.load(f)["presets"]


