# ФУНКЦИЯ: Создание гексагональной сетки H3
# ---------------------------------------------------------------------------

def create_h3_grid(bbox, resolution=9):
    """
    Создаёт гексагональную сетку H3 для покрытия заданной области.
    
    H3 обеспечивает:
    - Глобально уникальные идентификаторы ячеек
    - Иерархическую структуру (агрегация на разных уровнях)
    - Эффективные пространственные операции
    
    Параметры:
    ----------
    bbox : tuple
        Ограничивающий прямоугольник (west, south, east, north)
    
    resolution : int
        Разрешение сетки H3 (0-15)
        Чем больше значение, тем мельче ячейки
    
    Возвращает:
    -----------
    GeoDataFrame
        Таблица с колонками:
        - h3_index: строковый идентификатор ячейки H3
        - geometry: полигон гексагона
    
    Алгоритм:
    ---------
    1. Создать полигон из bbox
    2. Заполнить полигон индексами H3 (polyfill)
    3. Конвертировать индексы в геометрии
    4. Собрать в GeoDataFrame
    """
    # ------------------------------------
    # Шаг 1: Создание полигона из bbox
    # ------------------------------------
    # box(minx, miny, maxx, maxy) создаёт прямоугольник
    bbox_polygon = box(*bbox)  # *bbox распаковывает tuple в аргументы
    
    # ------------------------------------
    # Шаг 2: Заполнение полигона ячейками H3
    # ------------------------------------
    # polyfill_geojson возвращает множество индексов H3,
    # центры которых попадают внутрь полигона
    #
    # __geo_interface__ — стандартный способ получить GeoJSON из Shapely
    h3_indexes = list(h3.polyfill_geojson(
        bbox_polygon.__geo_interface__,
        resolution
    ))
    
    # ------------------------------------
    # Обработка краевого случая
    # ------------------------------------
    # Если область слишком мала, polyfill может вернуть пустой список
    if not h3_indexes:
        # Создаём одну ячейку в центре области
        west, south, east, north = bbox
        center_lat = (south + north) / 2
        center_lng = (west + east) / 2
        
        # geo_to_h3 возвращает индекс ячейки, содержащей точку
        h3_indexes = [h3.geo_to_h3(center_lat, center_lng, resolution)]
    
    # ------------------------------------
    # Шаг 3: Конвертация индексов в геометрии
    # ------------------------------------
    # h3_to_geo_boundary возвращает координаты вершин гексагона
    # geo_json=True — порядок координат [lon, lat] (не [lat, lon])
    h3_geometries = [
        Polygon(h3.h3_to_geo_boundary(h, geo_json=True))
        for h in h3_indexes
    ]
    
    # ------------------------------------
    # Шаг 4: Сборка GeoDataFrame
    # ------------------------------------
    h3_gdf = gpd.GeoDataFrame(
        {
            'h3_index': h3_indexes,     # Для связывания данных
            'geometry': h3_geometries    # Для пространственных операций
        },
        crs="EPSG:4326"  # H3 работает в географических координатах
    )
    
    # Перепроецируем для согласованности с данными OSM
    h3_gdf = h3_gdf.to_crs(CRS_PROJ)
    
    return h3_gdf


