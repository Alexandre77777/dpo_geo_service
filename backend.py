def load_osm_data(bbox, tags_config):
    """
    Загружает геоданные из OpenStreetMap для заданной области.
    
    Это ключевая функция интеграции с внешним API.
    OSMnx абстрагирует работу с Overpass API, предоставляя
    удобный Python-интерфейс.
    
    Параметры:
    ----------
    bbox : tuple
        Ограничивающий прямоугольник (west, south, east, north)
        Координаты в EPSG:4326 (градусы)
    
    tags_config : list[dict]
        Конфигурация слоёв для загрузки
    
    Возвращает:
    -----------
    dict[str, GeoDataFrame]
        Словарь: название_слоя → GeoDataFrame с объектами
        Все GeoDataFrame в системе координат EPSG:3857
    
    Особенности реализации:
    -----------------------
    - Каждый слой загружается независимо (отказоустойчивость)
    - Пустые слои не прерывают работу
    - Данные сразу перепроецируются в метрическую СК
    """
    # Распаковка координат bbox
    west, south, east, north = bbox
    
    # Словарь для накопления результатов
    data = {}
    
    # Итерируем по всем типам объектов из конфигурации
    for tag in tags_config:
        name = tag["name"]
        
        # Формируем словарь тегов для запроса к OSM
        # OSMnx принимает теги в формате {key: value}
        osm_tag = {tag["key"]: tag["value"]}
        
        print(f"Загрузка {name}...")
        
        try:
            # ------------------------------------
            # Запрос к OpenStreetMap через OSMnx
            # ------------------------------------
            # features_from_bbox загружает все объекты указанного типа
            # в пределах bounding box
            #
            # Под капотом:
            # 1. OSMnx формирует Overpass QL запрос
            # 2. Отправляет его к Overpass API
            # 3. Получает XML/JSON ответ
            # 4. Парсит в GeoDataFrame
            gdf = ox.features_from_bbox(
                (west, south, east, north),  # bbox в формате OSMnx
                tags=osm_tag                  # фильтр по тегам
            )
            
            # ------------------------------------
            # Перепроецирование в метрическую СК
            # ------------------------------------
            # Исходные данные OSM в EPSG:4326 (градусы)
            # Для расчёта буферов нужны метры → EPSG:3857
            gdf = gdf.to_crs(CRS_PROJ)
            
            # Сохраняем результат
            data[name] = gdf
            print(f"  Найдено: {len(gdf)} объектов")
            
        except Exception as e:
            # ------------------------------------
            # Обработка ошибок (отказоустойчивость)
            # ------------------------------------
            # Причины ошибок:
            # - Нет данных в OSM для этого региона
            # - Сетевые проблемы
            # - Таймаут Overpass API
            print(f"  Нет данных для {name}: {e}")
            
            # Создаём пустой GeoDataFrame для консистентности
            # Это позволяет остальному коду работать без проверок на None
            data[name] = gpd.GeoDataFrame(
                columns=['geometry'],
                crs=CRS_PROJ
            )
    
    return data


