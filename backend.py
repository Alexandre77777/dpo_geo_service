# ГЛАВНАЯ ФУНКЦИЯ: Запуск полного анализа
# ---------------------------------------------------------------------------

def run_analysis(bbox, tags_config, weights=None, h3_resolution=9):
    """
    Выполняет полный цикл геоанализа территории.
    
    Это точка входа в бэкенд — единственная функция,
    которую вызывает фронтенд. Реализует паттерн "Фасад",
    скрывая сложность внутренней логики.
    
    Этапы пайплайна:
    ----------------
    1. Загрузка данных из OSM
    2. Создание H3-сетки
    3. Буферный анализ ячеек
    4. Нормализация показателей
    5. Расчёт композитного индекса
    
    Параметры:
    ----------
    bbox : tuple
        Область анализа (west, south, east, north)
    
    tags_config : list[dict]
        Конфигурация слоёв
    
    weights : dict[str, float], optional
        Веса для расчёта индекса
        Ключи — названия слоёв, значения — веса [-1, 1]
    
    h3_resolution : int
        Разрешение сетки H3
    
    Возвращает:
    -----------
    tuple(GeoDataFrame, dict)
        - GeoDataFrame с результатами по ячейкам
        - Исходные данные OSM (для дополнительной визуализации)
    """
    
    # ═══════════════════════════════════════════════════════════
    # ЭТАП 1: Загрузка данных из OpenStreetMap
    # ═══════════════════════════════════════════════════════════
    print("=== Загрузка данных из OSM ===")
    data = load_osm_data(bbox, tags_config)
    
    # ═══════════════════════════════════════════════════════════
    # ЭТАП 2: Создание пространственной сетки H3
    # ═══════════════════════════════════════════════════════════
    print("=== Создание H3 сетки ===")
    h3_gdf = create_h3_grid(bbox, h3_resolution)
    print(f"Создано ячеек: {len(h3_gdf)}")
    
    # ═══════════════════════════════════════════════════════════
    # ЭТАП 3: Пространственный анализ каждой ячейки
    # ═══════════════════════════════════════════════════════════
    print("=== Анализ ячеек ===")
    
    # Список названий признаков для создания колонок
    feature_names = [tag["name"] for tag in tags_config]
    
    # Анализ каждой ячейки
    results_list = []
    for idx, row in h3_gdf.iterrows():
        cell_results = analyze_h3_cell(row.geometry, data, tags_config)
        results_list.append(cell_results)
    
    # Конвертация списка словарей в DataFrame
    results_df = pd.DataFrame(results_list)
    
    # Добавление результатов в GeoDataFrame
    for col in feature_names:
        if col in results_df.columns:
            h3_gdf[col] = results_df[col].values
        else:
            h3_gdf[col] = 0
    
    # ═══════════════════════════════════════════════════════════
    # ЭТАП 4: Нормализация показателей
    # ═══════════════════════════════════════════════════════════
    print("=== Нормализация ===")
    
    # MinMaxScaler приводит значения к диапазону [0, 1]
    # Формула: x_norm = (x - x_min) / (x_max - x_min)
    scaler = MinMaxScaler()
    
    # Нормализуем только если есть ненулевые значения
    if h3_gdf[feature_names].sum().sum() > 0:
        h3_gdf[feature_names] = scaler.fit_transform(h3_gdf[feature_names])
    
    # ═══════════════════════════════════════════════════════════
    # ЭТАП 5: Расчёт композитного индекса
    # ═══════════════════════════════════════════════════════════
    print("=== Расчёт индекса ===")
    
    if weights and any(weights.values()):
        # ------------------------------------
        # Взвешенный индекс
        # ------------------------------------
        # Пользователь задал приоритеты для разных типов объектов
        
        # Формируем массив весов в порядке признаков
        weights_array = np.array([
            weights.get(name, 1.0)
            for name in feature_names
        ])
        
        # Нормализуем веса, чтобы сумма = 1
        # Это гарантирует интерпретируемость индекса [0, 1]
        weights_array = weights_array / weights_array.sum()
        
        # Матричное умножение: взвешенная сумма
        # @ — оператор матричного умножения Python 3.5+
        h3_gdf['index_score'] = h3_gdf[feature_names].values @ weights_array
        
    else:
        # ------------------------------------
        # Простое суммирование
        # ------------------------------------
        # Все признаки равнозначны
        h3_gdf['index_score'] = h3_gdf[feature_names].sum(axis=1)
    
    print("=== Готово ===")
    
    return h3_gdf, data