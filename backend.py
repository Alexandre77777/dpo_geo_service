# ФУНКЦИЯ: Анализ одной ячейки H3
# ---------------------------------------------------------------------------

def analyze_h3_cell(geom, data, tags_config):
    """
    Выполняет буферный анализ для одной ячейки H3.
    
    Для каждого типа объектов:
    1. Создаётся буферная зона вокруг ячейки
    2. Находятся объекты, пересекающиеся с буфером
    3. Вычисляется метрика (количество/длина/площадь)
    
    Параметры:
    ----------
    geom : Polygon
        Геометрия анализируемой ячейки
    
    data : dict[str, GeoDataFrame]
        Данные OSM (результат load_osm_data)
    
    tags_config : list[dict]
        Конфигурация с радиусами буферов
    
    Возвращает:
    -----------
    dict[str, float]
        Метрики для каждого типа объектов
    
    Выбор метрики:
    --------------
    - Point → количество (сколько объектов доступно)
    - LineString → длина в метрах (протяжённость инфраструктуры)
    - Polygon → площадь в м² (размер доступной территории)
    """
    results = {}
    
    for tag in tags_config:
        name = tag["name"]
        
        # Получаем радиус буфера из конфигурации
        # Значение по умолчанию 800м для совместимости
        buffer_radius = tag.get("buffer", 800)
        
        # ------------------------------------
        # Создание буферной зоны
        # ------------------------------------
        # buffer() — метод Shapely, создающий полигон-буфер
        # Радиус в метрах благодаря проекции EPSG:3857
        buffer_zone = geom.buffer(buffer_radius)
        
        # Проверка наличия данных
        if name not in data or data[name].empty:
            results[name] = 0
            continue
        
        gdf = data[name]
        
        try:
            # ------------------------------------
            # Пространственный запрос
            # ------------------------------------
            # intersects() — проверка пересечения геометрий
            # Возвращает булеву маску для фильтрации
            intersecting = gdf[gdf.geometry.intersects(buffer_zone)]
            
            if intersecting.empty:
                results[name] = 0
                
            # ------------------------------------
            # Выбор метрики по типу геометрии
            # ------------------------------------
            elif intersecting.geometry.iloc[0].geom_type in ['Point', 'MultiPoint']:
                # Для точек: количество объектов
                results[name] = len(intersecting)
                
            elif intersecting.geometry.iloc[0].geom_type in ['LineString', 'MultiLineString']:
                # Для линий: суммарная длина
                results[name] = intersecting.geometry.length.sum()
                
            else:
                # Для полигонов: суммарная площадь
                results[name] = intersecting.geometry.area.sum()
                
        except:
            results[name] = 0
    
    return results


